import { isAnomaly, isSegmentation } from './frameworks';

/**
 * Image extensions an AnomalyFolder dataset accepts.
 *
 * anomalib reads through PIL, so a 16-bit TIFF is not guaranteed to survive;
 * `.tif` is listed because the importer counts such files, but the dataset
 * creation flow warns when it finds them. See docs/ANOMALY_DETECTION_DESIGN.md.
 */
export const ANOMALY_IMAGE_EXTENSIONS = ['.png', '.jpg', '.jpeg', '.bmp', '.tif', '.tiff'];

/**
 * anomalib uses the datamodule `name` to build result paths, so it must be a
 * safe path segment. Mirrors `toSafeSlug` without importing the fs-aware module.
 */
export function toDatamoduleName(name: string): string {
  const slug = name.trim().toLowerCase().replace(/[^a-z0-9._-]+/g, '_').replace(/^_+|_+$/g, '');
  return slug || 'anomaly_dataset';
}

// Generate dataset YAML content
export function generateDatasetYaml(dataset: {
  name: string;
  format: string;
  numClasses: number;
  datasetDir?: string | null;
  trainImagePath?: string | null;
  trainAnnoPath?: string | null;
  evalImagePath?: string | null;
  evalAnnoPath?: string | null;
  normalDir?: string | null;
  normalTestDir?: string | null;
  abnormalDir?: string | null;
  maskDir?: string | null;
  task?: string;
  framework?: string;
}): string {
  // Unsupervised anomaly detection: anomalib's Folder datamodule. Only
  // `normal_dir` is trained on; the abnormal/mask directories exist so the run
  // can be *evaluated* (and so a threshold can be picked at all).
  if (isAnomaly(dataset.framework)) {
    const root = (dataset.datasetDir || '').replace(/\\/g, '/');
    const lines = [
      `    name: ${toDatamoduleName(dataset.name)}`,
      `    root: ${root}`,
      `    normal_dir: ${dataset.normalDir || 'train_good'}`,
    ];
    if (dataset.normalTestDir) lines.push(`    normal_test_dir: ${dataset.normalTestDir}`);
    if (dataset.abnormalDir) lines.push(`    abnormal_dir: ${dataset.abnormalDir}`);
    if (dataset.maskDir) lines.push(`    mask_dir: ${dataset.maskDir}`);
    lines.push(
      `    extensions: ${JSON.stringify(ANOMALY_IMAGE_EXTENSIONS)}`,
      '    test_split_mode: from_dir',
      '    val_split_mode: from_test',
      '    val_split_ratio: 0.5',
      '    seed: 42',
    );

    return `# Dataset configuration for ${dataset.name}
# Generated by AutoTrain Platform (AnomalyFolder / anomalib)
#
# Training uses ${dataset.normalDir || 'train_good'} ONLY. The defect images are
# never trained on: they populate the test split, half of which anomalib takes as
# the validation split (val_split_ratio below) and uses to pick the anomaly-score
# threshold and normalise scores.
#
# Consequence worth knowing: metrics printed during training are computed on data
# that took part in choosing the threshold. For an unbiased number, run a
# validation job against a set of defect images that this dataset does not
# include.
${dataset.maskDir ? '' : '#\n# No mask_dir configured, so pixel_auroc / pixel_f1 will be absent. Add masks\n# for the defect images to get localisation metrics.\n'}
data:
  class_path: anomalib.data.Folder
  init_args:
${lines.join('\n')}
`;
  }

  // PaddleSeg datasets use list files (train.txt/val.txt) + num_classes.
  if (isSegmentation(dataset.framework)) {
    const root = dataset.datasetDir || '';
    const trainList = dataset.trainAnnoPath || 'train.txt';
    const valList = dataset.evalAnnoPath || 'val.txt';
    return `# Dataset configuration for ${dataset.name}
# Generated by AutoTrain Platform (PaddleSeg)

train_dataset:
  type: Dataset
  dataset_root: ${root}
  train_path: ${root}/${trainList}
  num_classes: ${dataset.numClasses}
  mode: train
  transforms:
    - type: Resize
      target_size: [512, 512]
    - type: RandomHorizontalFlip
    - type: Normalize

val_dataset:
  type: Dataset
  dataset_root: ${root}
  val_path: ${root}/${valList}
  num_classes: ${dataset.numClasses}
  mode: val
  transforms:
    - type: Normalize
`;
  }

  const baseDir = dataset.datasetDir || '';
  
  const trainImageDir = dataset.trainImagePath || 'train';
  const trainAnno = dataset.trainAnnoPath || 'annotations/instance_train.json';
  const evalImageDir = dataset.evalImagePath || 'val';
  const evalAnno = dataset.evalAnnoPath || 'annotations/instance_val.json';

  // Instance segmentation requires gt_poly so the data loader passes mask
  // polygons to the model (Mask R-CNN, SOLOv2, etc.).
  const dataFields = dataset.task === 'instance_segmentation'
    ? "['image', 'gt_bbox', 'gt_class', 'gt_poly', 'is_crowd']"
    : "['image', 'gt_bbox', 'gt_class', 'is_crowd']";

  let yaml = `# Dataset configuration for ${dataset.name}
# Generated by AutoTrain Platform
# Task: ${dataset.task || 'detection'}

metric: ${dataset.format}
num_classes: ${dataset.numClasses}

TrainDataset:
  name: COCODataSet
  image_dir: ${trainImageDir}
  anno_path: ${trainAnno}
  dataset_dir: ${baseDir}
  data_fields: ${dataFields}

EvalDataset:
  name: COCODataSet
  image_dir: ${evalImageDir}
  anno_path: ${evalAnno}
  dataset_dir: ${baseDir}
  allow_empty: true

TestDataset:
  name: ImageFolder
  anno_path: ${evalAnno}
  dataset_dir: ${baseDir}
`;

  return yaml;
}

